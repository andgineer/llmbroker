"""The lineup file: rendered wholesale from configs, written atomically.

The file is llmbroker's own — see ``specs/reference/rules/sync-merge.md``.
"""

from collections.abc import Iterable, Mapping
from dataclasses import dataclass
from pathlib import Path
from types import MappingProxyType

import tomli_w

from llmbroker.broker.aliases import AliasRefresh, AliasTarget
from llmbroker.broker.keys import KeyProbe
from llmbroker.broker.merge import SyncSource, merge_lineup
from llmbroker.models import KeyInfo, Lineup, LLMConfig, SyncReport
from llmbroker.protocols.store import StoreProtocol
from llmbroker.standalone.registry import read_lineup
from llmbroker.util.atomic import write_atomic

_HEADER = (
    "# Generated by llmbroker — rewritten in full on every sync.\n"
    "# Add your own models with `llmbroker add-model`, not by editing this file."
)
_NO_TARGETS: Mapping[str, AliasTarget] = MappingProxyType({})


def entry_block(section: str, entry: dict) -> str:
    """One ``[[section]]`` block. The header is written here rather than left to
    ``tomli_w``, which renders a short array of tables as an inline top-level key —
    written after a trailing ``[keys.*]`` table that parses as a member of that table."""
    return f"[[{section}]]\n{tomli_w.dumps(entry).rstrip()}"


def _entry_dict(cfg: LLMConfig) -> dict:
    entry: dict = {}
    if cfg.alias is not None:
        entry["alias"] = cfg.alias
    entry["name"] = cfg.name
    entry["model"] = cfg.model
    entry["base_url"] = cfg.base_url
    entry["api_key_ref"] = cfg.api_key_ref
    if cfg.parallel is not None:
        entry["parallel"] = cfg.parallel
    if cfg.weight:
        entry["weight"] = cfg.weight
    return entry


def key_block(info: KeyInfo) -> dict:
    """One ``[keys.REF]`` table: the help plus whatever else the section carried,
    which is a documented passthrough and has to survive the round trip."""
    table: dict = {**info.extra}
    if info.help:
        table["help"] = info.help
    return table


def _keys_table(configs: Iterable[LLMConfig], keys: dict[str, KeyInfo]) -> dict:
    """The ``[keys]`` the rendered entries need. A ref nothing references any more
    carries no help worth keeping — the entry that wanted it is gone."""
    table: dict = {}
    for cfg in configs:
        ref = cfg.api_key_ref
        if not ref or ref in table or ref not in keys:
            continue
        block = key_block(keys[ref])
        if block:
            table[ref] = block
    return table


def render_lineup(lineup: Lineup) -> str:
    """The whole file: pool entries, then the alias-following ones, then ``[keys]``.

    Nothing is carried over from the previous text, so there is nothing to verify
    the result against.
    """
    parts = [_HEADER]
    parts.extend(entry_block("llms", _entry_dict(c)) for c in lineup.configs if not c.custom)
    parts.extend(entry_block("custom", _entry_dict(c)) for c in lineup.configs if c.custom)
    table = _keys_table(lineup.configs, lineup.keys)
    if table:
        parts.append(tomli_w.dumps({"keys": table}).rstrip("\n"))
    return "\n\n".join(parts) + "\n"


def write_lineup(path: Path, lineup: Lineup) -> bool:
    """Render and write, and say whether the file changed.

    Compared on the exact bytes that would be written, so an upstream change
    carrying only a key hint still counts: the file's git history is the record.
    """
    rendered = render_lineup(lineup)
    if path.exists() and path.read_text(encoding="utf-8") == rendered:
        return False
    write_atomic(path, rendered)
    return True


@dataclass(frozen=True, slots=True)
class FileSyncOutcome:
    """The result of syncing the file: the report, whether it was rewritten, the
    merged lineup, and what the alias refresh found."""

    report: SyncReport
    changed: bool
    configs: tuple[LLMConfig, ...] = ()
    refresh: AliasRefresh = AliasRefresh(key_help={})


async def sync_lineup_file(
    path: Path,
    src: SyncSource,
    *,
    probe: KeyProbe,
    store: StoreProtocol | None = None,
    alias_targets: Mapping[str, AliasTarget] = _NO_TARGETS,
) -> FileSyncOutcome:
    """Merge ``src`` into the lineup file at ``path`` and rewrite it.

    Any error leaves the file untouched.
    """
    if path.suffix.lower() != ".toml":
        raise ValueError(f"sync target must be a .toml file, got {path}")
    outcome = await merge_lineup(
        src,
        read_lineup(path),
        probe=probe,
        store=store,
        alias_targets=alias_targets,
    )
    return FileSyncOutcome(
        report=outcome.report,
        changed=write_lineup(path, outcome.lineup),
        configs=tuple(outcome.lineup.configs),
        refresh=outcome.refresh,
    )
